#!/usr/bin/env node
// Builds what Kakiaji's preview needs to show a document exactly as a blog post on afterai.dev:
//
//   blog-markdown.js  the site's Markdown renderer (src/lib/blog-markdown/), one script for JavaScriptCore;
//                     it defines globalThis.BlogMarkdown.render(markdown, imageBase)
//   blog.css          the site's stylesheet (global.css + article.css) with Inter embedded,
//                     since the preview runs offline and the site loads Inter from Google Fonts
//
// Usage: pnpm build:renderer [out-dir]   (default: dist-renderer/). Kakiaji's `make sync-renderer` runs this.
import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = resolve(process.argv[2] ?? join(root, 'dist-renderer'));
await mkdir(out, { recursive: true });

await build({
  entryPoints: [join(root, 'src/lib/blog-markdown/kakiaji.ts')],
  outfile: join(out, 'blog-markdown.js'),
  bundle: true,
  format: 'iife',
  platform: 'neutral',
  mainFields: ['module', 'main'],
  // JavaScriptCore of macOS 15 (Safari 18).
  target: 'safari18',
  minify: true,
  legalComments: 'eof',
  logLevel: 'warning',
});

const require = createRequire(import.meta.url);
const interDir = dirname(require.resolve('@fontsource-variable/inter/package.json'));
const inter = await readFile(join(interDir, 'files/inter-latin-wght-normal.woff2'));
const fontFace = `/* Inter (SIL Open Font License 1.1), embedded for the offline preview. */
@font-face {
  font-family: 'Inter';
  font-style: normal;
  font-weight: 100 900;
  font-display: block;
  src: url(data:font/woff2;base64,${inter.toString('base64')}) format('woff2');
}
`;
const css = [
  '/* Generated by scripts/build-blog-renderer.mjs in AfterAILab.github.io. Do not edit; run make sync-renderer. */',
  fontFace,
  await readFile(join(root, 'src/styles/global.css'), 'utf8'),
  await readFile(join(root, 'src/styles/article.css'), 'utf8'),
].join('\n');
await writeFile(join(out, 'blog.css'), css);

console.log(`wrote ${join(out, 'blog-markdown.js')} and ${join(out, 'blog.css')}`);
